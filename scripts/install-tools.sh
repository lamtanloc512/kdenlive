#!/usr/bin/env bash
# Installs melt, ffmpeg and ffprobe for kdenlive-mcp, taken from the official Kdenlive 26.08.3 release,
# so titles, transitions and renders behave exactly like Kdenlive.
#
#   scripts/install-tools.sh             # from bundled-tools/ in this repo (Linux x86_64, macOS arm64)
#   scripts/install-tools.sh --download  # download the full Kdenlive release from download.kde.org instead
#   KDENLIVE_VERSION=26.08.2 scripts/install-tools.sh --download
#
# Result: ~/.kdenlive-mcp/tools/bin/{melt,ffmpeg,ffprobe}. kdenlive-mcp finds them there automatically
# (MELT_PATH / FFMPEG_PATH / FFPROBE_PATH still win if you set them).
# Disk: bundled ~150 MB (Linux) / ~115 MB (macOS); --download ~750 MB / ~600 MB.
set -euo pipefail

report() {
  echo
  echo "installed into $DEST"
  for exe in melt ffprobe ffmpeg; do
    if [ -x "$DEST/bin/$exe" ]; then
      printf '  %-8s %s\n' "$exe" "$("$DEST/bin/$exe" -version 2>&1 | grep -m1 -iE "^(melt|ffmpeg|ffprobe) " || echo '?')"
    fi
  done
  if [ -x "$DEST/bin/melt" ]; then
    n="$("$DEST/bin/melt" -query producers 2>/dev/null | grep -c kdenlivetitle || true)"
    if [ "$n" -gt 0 ]; then echo "  titles: supported (kdenlivetitle found)"; else echo "  warning: this melt has no kdenlivetitle producer" >&2; fi
  fi
}

DEST="${KDENLIVE_MCP_TOOLS:-$HOME/.kdenlive-mcp/tools}"
REPO_TOOLS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/bundled-tools"
case "$(uname -s)/$(uname -m)" in
  Linux/x86_64) BUNDLE=kdenlive-mcp-tools-linux-x64 ;;
  Darwin/arm64) BUNDLE=kdenlive-mcp-tools-macos-arm64 ;;
  *) BUNDLE="" ;;
esac
if [ "${1:-}" != "--download" ] && [ -n "$BUNDLE" ] && [ -f "$REPO_TOOLS/$BUNDLE.tar.xz" ]; then
  echo "installing $BUNDLE from $REPO_TOOLS"
  mkdir -p "$DEST/bin"
  rm -rf "${DEST:?}/$BUNDLE"
  tar -xJf "$REPO_TOOLS/$BUNDLE.tar.xz" -C "$DEST"
  [ "$(uname -s)" = Darwin ] && xattr -dr com.apple.quarantine "$DEST/$BUNDLE" 2>/dev/null || true
  for exe in melt ffmpeg ffprobe; do ln -sf "$DEST/$BUNDLE/bin/$exe" "$DEST/bin/$exe"; done
  report
  exit 0
fi

VERSION="${KDENLIVE_VERSION:-26.08.3}"
SERIES="${VERSION%.*}"
BASE="https://download.kde.org/stable/kdenlive/$SERIES"
OS="$(uname -s)"
ARCH="$(uname -m)"

case "$OS/$ARCH" in
  Linux/x86_64)  FILE="kdenlive-$VERSION-x86_64.AppImage"; URL="$BASE/linux/$FILE" ;;
  Darwin/arm64)  FILE="kdenlive-$VERSION-arm64.dmg";       URL="$BASE/macOS/$FILE" ;;
  Darwin/x86_64) FILE="kdenlive-$VERSION-x86_64.dmg";      URL="$BASE/macOS/$FILE" ;;
  *) echo "unsupported platform $OS/$ARCH (supported: Linux x86_64, macOS arm64/x86_64)" >&2; exit 1 ;;
esac

sha256() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -c1-64; else shasum -a 256 "$1" | cut -c1-64; fi; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
echo "downloading $URL"
curl -fL --progress-bar -o "$TMP/$FILE" "$URL"
EXPECTED="$(curl -fsSL "$URL.sha256" | grep -oE '[0-9a-f]{64}' | head -1 || true)"
ACTUAL="$(sha256 "$TMP/$FILE")"
if [ -z "$EXPECTED" ]; then
  echo "warning: no published checksum found at $URL.sha256; sha256 is $ACTUAL" >&2
elif [ "$EXPECTED" != "$ACTUAL" ]; then
  echo "checksum mismatch for $FILE: expected $EXPECTED, got $ACTUAL" >&2; exit 1
else
  echo "checksum ok ($ACTUAL)"
fi

mkdir -p "$DEST/bin"
TARGET="$DEST/kdenlive-$VERSION"
rm -rf "$TARGET"

wrapper() { # name, script body
  printf '#!/usr/bin/env bash\n# generated by kdenlive-mcp scripts/install-tools.sh (Kdenlive %s)\n%s\n' "$VERSION" "$2" > "$DEST/bin/$1"
  chmod +x "$DEST/bin/$1"
}

if [ "$OS" = Linux ]; then
  chmod +x "$TMP/$FILE"
  (cd "$TMP" && "./$FILE" --appimage-extract >/dev/null)
  mv "$TMP/squashfs-root" "$TARGET"
  for exe in melt ffmpeg ffprobe; do
    if [ -x "$TARGET/usr/bin/$exe" ]; then
      wrapper "$exe" "root='$TARGET'
source \"\$root/apprun-hooks/craft-runenv-hook.sh\"
exec \"\$root/usr/bin/$exe\" \"\$@\""
    else
      echo "warning: $exe not in this AppImage; install it with your package manager" >&2
    fi
  done
else
  MNT="$TMP/mnt"
  mkdir -p "$MNT"
  hdiutil attach -nobrowse -readonly -mountpoint "$MNT" "$TMP/$FILE" >/dev/null
  APP="$(ls -d "$MNT"/*.app | head -1)"
  mkdir -p "$TARGET"
  cp -R "$APP" "$TARGET/"
  hdiutil detach "$MNT" >/dev/null
  APP="$TARGET/$(basename "$APP")"
  xattr -dr com.apple.quarantine "$APP" 2>/dev/null || true
  C="$APP/Contents"
  for exe in melt ffmpeg ffprobe; do
    if [ -x "$C/MacOS/$exe" ]; then
      wrapper "$exe" "C='$C'
# point MLT at the modules inside the bundle (layout differs between releases)
for d in PlugIns/mlt Frameworks/mlt lib/mlt-7 Resources/lib/mlt-7; do [ -d \"\$C/\$d\" ] && export MLT_REPOSITORY=\"\${MLT_REPOSITORY:-\$C/\$d}\"; done
for d in Resources/mlt Resources/share/mlt-7 share/mlt-7; do [ -d \"\$C/\$d\" ] && export MLT_DATA=\"\${MLT_DATA:-\$C/\$d}\"; done
[ -n \"\${MLT_DATA:-}\" ] && [ -d \"\$MLT_DATA/profiles\" ] && export MLT_PROFILES_PATH=\"\${MLT_PROFILES_PATH:-\$MLT_DATA/profiles}\"
for d in PlugIns/frei0r-1 lib/frei0r-1; do [ -d \"\$C/\$d\" ] && export FREI0R_PATH=\"\${FREI0R_PATH:-\$C/\$d}\"; done
exec \"\$C/MacOS/$exe\" \"\$@\""
    else
      echo "warning: $exe not in the app bundle; install it with: brew install ffmpeg" >&2
    fi
  done
fi

report
